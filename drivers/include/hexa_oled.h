#ifndef HEXA_OLED_H
#define HEXA_OLED_H

#include "stdint.h"

#include "hexa_types.h"
#include "hexa_i2c.h"

/* Монохромный OLED на SSD1306, размер задан HEXA_OLED_WIDTH/HEIGHT.
 *
 * Рисование идёт в буфер кадра в оперативной памяти, а не сразу в
 * дисплей. Пока не вызван hexa_oled_flush(), на экране ничего не
 * меняется. Отсюда обычный порядок работы:
 *
 *      hexa_oled_clear();
 *      hexa_oled_print("hello", 0, 0, 1);
 *      hexa_oled_flush();
 *
 * Координаты: x вправо, y вниз, начало в левом верхнем углу.
 * color: 0 — погасить, 1 — зажечь, любое другое значение — инвертировать.
 */

hexa_status_t hexa_oled_init(void);

/* Шрифт 5x7, шаг между символами 6 пикселей. Строка обрезается по
 * правому краю экрана. Непечатаемые символы и кириллица выводятся
 * пробелом — в шрифте только ASCII 0x20..0x7E. */
hexa_status_t hexa_oled_print(const char* str, uint8_t x, uint8_t y, uint8_t color);

hexa_status_t hexa_oled_pixel(uint8_t x, uint8_t y, uint8_t color);

/* Гасит буфер кадра. На экран не влияет до flush. */
hexa_status_t hexa_oled_clear(void);

/* Выгружает буфер кадра в дисплей — единственное место, где картинка
 * реально обновляется. Передаёт килобайт по шине, так что дёргать это
 * чаще, чем нужно для анимации, смысла нет. */
hexa_status_t hexa_oled_flush(void);


/* ---- Геометрия -------------------------------------------------------
 *
 * Координаты здесь знаковые, в отличие от hexa_oled_pixel(): фигура
 * может частично уходить за любой край, видимая часть рисуется, всё
 * остальное отсекается. Это и есть причина разницы в типах — с uint8_t
 * не выразить "прямоугольник начинается за левым краем", а без такого
 * не сделать ни прокрутку, ни панорамирование.
 *
 * Возврат:
 *   HEXA_ERR_PARAM — размер <= 0 или NULL-указатель, до буфера не дошло;
 *   HEXA_OK        — всё остальное, включая случай, когда фигура целиком
 *                    за экраном и рисовать было нечего.
 *
 * Про color == 2 (инверсия): каждая функция гарантирует, что любой
 * пиксель фигуры трогается ровно один раз, иначе инверсия сама себя бы
 * отменяла на пересечениях. Если рисуешь инверсией сам — следи за этим.
 */

/* Горизонтальный и вертикальный отрезки — отдельно от hexa_oled_line()
 * не для красоты: они пишут в буфер побайтово, минуя перебор пикселей,
 * и на заливке разница ощутима. Из них же собраны rect и fill_*. */
hexa_status_t hexa_oled_hline(int16_t x, int16_t y, int16_t w, uint8_t color);
hexa_status_t hexa_oled_vline(int16_t x, int16_t y, int16_t h, uint8_t color);

/* Произвольный отрезок, алгоритм Брезенхэма. Строго горизонтальный и
 * строго вертикальный случаи уходят в hline/vline. */
hexa_status_t hexa_oled_line(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint8_t color);

/* Прямоугольник: x,y — левый верхний угол, w,h — размеры в пикселях
 * (w=10 значит занятые столбцы x..x+9). rect рисует контур внутри этих
 * границ, fill_rect закрашивает всё. */
hexa_status_t hexa_oled_rect(int16_t x, int16_t y, int16_t w, int16_t h, uint8_t color);
hexa_status_t hexa_oled_fill_rect(int16_t x, int16_t y, int16_t w, int16_t h, uint8_t color);

/* Окружность с центром (cx,cy) и радиусом r, алгоритм средней точки.
 * r == 0 — одна точка. Диаметр получается 2*r+1. */
hexa_status_t hexa_oled_circle(int16_t cx, int16_t cy, int16_t r, uint8_t color);
hexa_status_t hexa_oled_fill_circle(int16_t cx, int16_t cy, int16_t r, uint8_t color);

/* Картинка из массива в ПЗУ.
 *
 * Формат — построчный, старший бит первый: каждая строка занимает
 * (w + 7) / 8 байт, бит 0x80 первого байта — самый левый пиксель,
 * хвост последнего байта игнорируется. Так по умолчанию отдают
 * конвертеры вроде image2cpp, и так же картинку видно глазами прямо
 * в исходнике, если писать её двоичными литералами:
 *
 *      static const uint8_t heart[] = {
 *              0b01101100,
 *              0b11111110,
 *              0b11111110,
 *              0b01111100,
 *              0b00111000,
 *              0b00010000,
 *      };
 *      hexa_oled_bitmap(60, 28, 8, 6, heart, 1);
 *
 * Единичные биты рисуются цветом color, нулевые не трогаются вообще —
 * картинка прозрачная и ложится поверх готового кадра. Нужен
 * непрозрачный фон — сначала hexa_oled_fill_rect() той же области. */
hexa_status_t hexa_oled_bitmap(int16_t x, int16_t y, int16_t w, int16_t h,
                               const uint8_t *bits, uint8_t color);

#endif // HEXA_OLED_H
