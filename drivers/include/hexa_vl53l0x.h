#ifndef HEXA_VL53L0X_H
#define HEXA_VL53L0X_H

#include <stdint.h>
#include <stdbool.h>

#include "hexa_types.h"

/* ST VL53L0X — лазерный дальномер (модуль GY-530).
 *
 * У чипа нет публичной карты регистров: последовательность инициализации
 * восстановлена по официальному API и в значительной части представляет
 * собой магические записи, которые нельзя обосновать по даташиту.
 * Реализован минимум, дающий рабочее одиночное измерение: data init,
 * заводской набор tuning-настроек и опорная калибровка (VHV + phase).
 *
 * Переконфигурация опорных SPAD не делается — используются значения,
 * загруженные чипом из NVM при включении. Для типового применения этого
 * достаточно; ценой будет несколько худшая устойчивость на пределе
 * дальности. Профиль по умолчанию — примерно до 1.2 м.
 */

hexa_status_t hexa_vl53l0x_init(void);
hexa_status_t hexa_vl53l0x_whoami(uint8_t *id);  /* 0xEE для VL53L0X */

/* Запустить одно измерение. Результат готов примерно через 30 мс. */
hexa_status_t hexa_vl53l0x_start(void);
hexa_status_t hexa_vl53l0x_ready(bool *ready);

/* Забрать дистанцию в миллиметрах и сбросить флаг прерывания.
 *
 * Возвращает HEXA_ERR, если чип пометил измерение недостоверным —
 * цель вне диапазона, слишком мало отражённого сигнала и т.п. В этом
 * случае *mm всё равно заполняется сырым значением (обычно 8190),
 * так что различать "нет цели" и ошибку шины можно по коду возврата. */
hexa_status_t hexa_vl53l0x_get(uint16_t *mm);

/* start + опрос готовности + get. Блокирует вызывающего до ~100 мс. */
hexa_status_t hexa_vl53l0x_measure(uint16_t *mm);

#endif // HEXA_VL53L0X_H
