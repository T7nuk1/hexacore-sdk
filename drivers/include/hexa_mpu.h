#ifndef MPU6050_H
#define MPU6050_H

#include <stdint.h>

#include "hexa_types.h"

/* MPU6050 — акселерометр и гироскоп на одном кристалле.
 *
 * Значения отдаются сырыми, как их выдаёт АЦП чипа: знаковые 16 бит,
 * без перевода в g и градусы в секунду. Перевод зависит от выбранного
 * диапазона измерения, а драйвер оставляет заводской: +-2g для
 * акселерометра (16384 единицы на g) и +-250 град/с для гироскопа
 * (131 единица на градус в секунду). */

/* Сбрасывает чип, выводит из сна и запускает все три оси.
 * Внутри ждёт 100 мс после сброса. */
hexa_status_t hexa_mpu_init(void);

/* Идентификатор чипа, для MPU6050 — 0x68. Удобно вызывать до init,
 * чтобы отличить "датчик не подключён" от "датчик не настроился". */
hexa_status_t hexa_mpu_whoami(uint8_t *id);

hexa_status_t hexa_mpu_read_accel(int16_t *x, int16_t *y, int16_t *z);
hexa_status_t hexa_mpu_read_gyro(int16_t *gx, int16_t *gy, int16_t *gz);


#endif // MPU6050_H
