#ifndef HEXA_BUTTON_H
#define HEXA_BUTTON_H

#include <stdint.h>
#include <stdbool.h>

#include "hexa_types.h"
#include "hexa_board.h"

/* Кнопки платы. Номер n — индекс в hexa_pins_buttons[] из hexa_board.c,
 * считая с нуля; всего BOARD_BTN_COUNT штук.
 *
 * Дребезг подавляется счётчиком: состояние меняется только после
 * четырёх подряд одинаковых опросов. Поэтому весь драйвер держится на
 * регулярном вызове hexa_button_scan(). */

hexa_status_t hexa_buttons_init(void);

/* Опрашивает все кнопки и обновляет их состояние.
 *
 * Дребезг гасится счётчиком на четыре опроса, поэтому задержка реакции —
 * ровно четыре периода, и на нажатие, и на отпускание. Отсюда выбор
 * периода: реже 10 мс — кнопки заметно тормозят, чаще 1 мс — окно
 * подавления дребезга становится короче самого дребезга, и он пролезает.
 *
 * Под FreeRTOS нижняя граница жёстче и задана тиком ядра. При
 * configTICK_RATE_HZ = 100 тик равен 10 мс, а pdMS_TO_TICKS(5) даёт ноль:
 * vTaskDelay(0) — это не задержка, а уступка процессора, и задача опроса
 * начнёт крутиться вхолостую. Поэтому в задаче период берётся не меньше
 * одного тика — 10 мс, реакция около 40 мс. Незаметно для пальца.
 *
 * В bare metal задержка идёт через таймер SCR1 и такого ограничения нет:
 * там период можно ставить и в 1 мс. */
void hexa_button_scan(void);

/* Кнопка нажата прямо сейчас. Пока держат — возвращает true. */
bool hexa_button_down(uint8_t n);

/* Кнопку нажали с прошлого вызова. Возвращает true ровно один раз на
 * каждое нажатие: факт события сбрасывается при чтении. */
bool hexa_button_pressed(uint8_t n);

#endif // HEXA_BUTTON_H
